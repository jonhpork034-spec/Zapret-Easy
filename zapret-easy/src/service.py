class ServiceManager:
    """Управляет zapret-easy.service из обычного пользователя."""

    def __init__(self, manager: StrategyManager | None = None) -> None:
        self.manager = manager or StrategyManager()

    # -- статус ------------------------------------------------------------
    def status(self) -> ServiceStatus:
        systemctl = _tool("systemctl")
        unit_exists = UNIT_PATH.is_file()
        ours = unit_exists and _unit_is_ours()
        active_state = _systemctl_state(systemctl, "is-active", SERVICE_NAME)
        enabled_state = _systemctl_state(systemctl, "is-enabled", SERVICE_NAME)
        package_active = (
            _systemctl_state(systemctl, "is-active", PACKAGE_SERVICE) == "active"
        )
        package_enabled_state = _systemctl_state(
            systemctl,
            "is-enabled",
            PACKAGE_SERVICE,
        )
        package_enabled = package_enabled_state in {
            "enabled",
            "enabled-runtime",
        }
        active = active_state == "active"
        enabled = enabled_state in {"enabled", "enabled-runtime"}

        if not unit_exists:
            detail = "не установлена"
        elif not ours:
            detail = "установлена сторонняя служба с тем же именем"
        elif active:
            detail = "активна" + (", включена" if enabled else ", не включена")
        else:
            detail = "установлена, не запущена" + (
                ", включена" if enabled else ""
            )
        if package_active:
            detail += "; zapret2.service активна"
        elif package_enabled:
            detail += "; zapret2.service включена"

        return ServiceStatus(
            installed=unit_exists,
            ours=ours,
            active=active,
            enabled=enabled,
            unit_path=UNIT_PATH,
            active_state=active_state,
            enabled_state=enabled_state,
            package_active=package_active,
            package_enabled=package_enabled,
            detail=detail,
        )

    # -- предварительная проверка -----------------------------------------
    def preflight(self) -> ServicePreflight:
        errors: list[str] = []
        warnings: list[str] = []
        status = self.status()

        user_name = _current_user_name()
        if user_name is None:
            errors.append("Не удалось определить текущего пользователя.")
        elif os.geteuid() == 0:
            errors.append(
                "TUI нужно запускать от обычного пользователя, а не root. "
                "root-операции выполняются через sudo -n."
            )

        nfqws2 = _find_nfqws2()
        if nfqws2 is None:
            errors.append(
                "nfqws2 не найден. Сначала установите пакет zapret2."
            )

        if not ZAPRET_INIT.is_file() or not os.access(ZAPRET_INIT, os.X_OK):
            errors.append(
                f"Не найден исполняемый init-скрипт zapret2: {ZAPRET_INIT}."
            )
        if not ZAPRET_LUA_DIR.is_dir():
            errors.append(f"Не найден каталог Lua-библиотек: {ZAPRET_LUA_DIR}.")
        else:
            for name in LUA_INIT_FILES:
                if not (ZAPRET_LUA_DIR / name).is_file():
                    errors.append(f"Не найдена Lua-библиотека zapret2: {name}.")
        if not (
            ZAPRET_CONFIG_SOURCE.is_file()
            or ZAPRET_CONFIG_DEFAULT.is_file()
        ):
            errors.append(
                "Не найден конфиг zapret2: "
                f"{ZAPRET_CONFIG_SOURCE} или {ZAPRET_CONFIG_DEFAULT}."
            )

        if _tool("nft") is None:
            errors.append("nft не найден. Установите nftables.")
        if _tool("systemctl") is None:
            errors.append("systemctl не найден. Проверьте systemd.")
        if os.geteuid() != 0 and _tool("sudo") is None:
            errors.append("sudo не найден: нельзя выполнить root-операции. " + SUDO_HINT)

        if status.package_active:
            errors.append(
                "Служба zapret2.service активна. Остановите и отключите её: "
                "sudo systemctl disable --now zapret2.service"
            )
        elif status.package_enabled:
            errors.append(
                "Служба zapret2.service включена и запустится при загрузке. "
                "Отключите её: sudo systemctl disable --now zapret2.service"
            )
        if status.installed and not status.ours:
            errors.append(
                f"{UNIT_PATH} уже существует и создан не zapret-easy. "
                "Удалите файл вручную."
            )
        if status.enabled_state == "masked":
            errors.append(
                f"{SERVICE_NAME} замаскирована. Снимите маску: "
                f"sudo systemctl unmask {SERVICE_NAME}"
            )
        if (
            _tool("systemctl") is not None
            and status.active_state == "unknown"
            and status.enabled_state == "unknown"
        ):
            errors.append(
                "systemd не отвечает. Убедитесь, что система загружена "
                "через systemd и systemctl работает."
            )
        if status.active:
            warnings.append(
                "Служба zapret-easy уже активна; установка перезапустит её."
            )

        strategy_name: str | None = None
        strategy_lua: Path | None = None
        strategies_dir: Path | None = None
        strategy_args: tuple[str, ...] = ()
        ports_tcp = ""
        ports_udp = ""

        if user_name is not None:
            strategy = self.manager.active_strategy()
            if strategy is None:
                errors.append(
                    "Не выбрана активная стратегия. Сначала выберите её "
                    "в пункте «Управление стратегиями»."
                )
            else:
                strategy_name = strategy.name
                strategy_lua = strategy.path
                strategies_dir = self.manager.strategies_dir
                validation = self.manager.validate(strategy)
                if not validation.valid:
                    errors.extend(validation.errors)
                else:
                    warnings.extend(validation.warnings)
                if not strategy.profile.error:
                    if not strategy.profile.args:
                        errors.append(
                            f"В профиле {strategy.profile.path.name} нет "
                            "аргументов nfqws2. Службу нельзя запустить."
                        )
                    else:
                        strategy_args = strategy.profile.args
                        try:
                            ports_tcp, ports_udp = derive_firewall_ports(
                                strategy_args
                            )
                        except ServiceError as exc:
                            errors.append(str(exc))

        if os.geteuid() != 0 and not errors:
            warnings.append(
                "Для установки/изменения службы потребуется подтверждение "
                "sudo -n. Пароль не запрашивается."
            )

        return ServicePreflight(
            errors=tuple(errors),
            warnings=tuple(warnings),
            status=status,
            user=user_name,
            strategy_name=strategy_name,
            strategy_lua=strategy_lua,
            strategies_dir=strategies_dir,
            strategy_args=strategy_args,
            nfqws2=nfqws2,
            ports_tcp=ports_tcp,
            ports_udp=ports_udp,
        )

    # -- действия ----------------------------------------------------------
    def install(self, preflight: ServicePreflight | None = None) -> ServiceResult:
        preflight = preflight or self.preflight()
        if not preflight.ok:
            return ServiceResult(
                ok=False,
                action="install",
                message="\n".join(preflight.errors),
            )
        assert preflight.user is not None
        assert preflight.strategy_name is not None
        assert preflight.strategy_lua is not None
        assert preflight.strategies_dir is not None
        plan = {
            "version": 1,
            "action": "install",
            "user": preflight.user,
            "strategy": {
                "name": preflight.strategy_name,
                "lua_path": str(preflight.strategy_lua),
                "strategies_dir": str(preflight.strategies_dir),
                "args": list(preflight.strategy_args),
            },
        }
        return self._run_root(plan)

    def start(self) -> ServiceResult:
        status = self.status()
        if status.package_active:
            return ServiceResult(
                False,
                "start",
                "Нельзя запускать второй nfqws2: zapret2.service активна. "
                "Остановите её: sudo systemctl disable --now zapret2.service",
            )
        if status.package_enabled:
            return ServiceResult(
                False,
                "start",
                "zapret2.service включена и запустится при загрузке. "
                "Отключите её: sudo systemctl disable --now zapret2.service",
            )
        if not status.installed:
            return ServiceResult(
                False,
                "start",
                "Служба ещё не установлена. Сначала выполните установку.",
            )
        if not status.ours:
            return ServiceResult(
                False,
                "start",
                f"{UNIT_PATH} создан не zapret-easy.",
            )
        if status.active:
            return ServiceResult(
                True,
                "start",
                "Служба zapret-easy уже запущена.",
            )
        return self._run_root({"version": 1, "action": "start"})

    def stop(self) -> ServiceResult:
        return self._run_root({"version": 1, "action": "stop"})

    def disable_all(self) -> ServiceResult:
        """Останавливает и отключает все известные zapret-службы."""
        return self._run_root({"version": 1, "action": "disable_all"})

    def rollback(self) -> ServiceResult:
        return self._run_root({"version": 1, "action": "rollback"})

    # -- запуск root-worker-а ---------------------------------------------
    def _run_root(self, plan: dict[str, Any]) -> ServiceResult:
        if os.geteuid() == 0:
            try:
                action, install_plan = _validate_plan(plan)
                return _execute_plan(action, install_plan)
            except ServiceError as exc:
                return ServiceResult(
                    False,
                    str(plan.get("action", "")),
                    str(exc),
                    output=exc.output,
                )
            except Exception as exc:  # noqa: BLE001 - защита TUI
                logger.exception("Ошибка прямой root-операции службы")
                return ServiceResult(
                    False,
                    str(plan.get("action", "")),
                    f"{type(exc).__name__}: {exc}",
                )

        sudo = _tool("sudo")
        if sudo is None:
            return ServiceResult(
                False,
                str(plan.get("action", "")),
                "sudo не найден: root-операции невозможны. " + SUDO_HINT,
            )

        bootstrap = (
            "import sys; "
            f"sys.path.insert(0, {str(PROJECT_ROOT)!r}); "
            "from src.service import worker_main; "
            "raise SystemExit(worker_main())"
        )
        python = Path(sys.executable)
        if not python.is_absolute():
            resolved = shutil.which("python3")
            python = Path(resolved) if resolved else python
        command = [
            "sudo",
            "-n",
            str(python),
            "-c",
            bootstrap,
            "--worker",
        ]
        action = str(plan.get("action", "service"))
        if action == "start":
            # sudo -n не должен ждать пароль; таймаут оставляем с запасом
            # на сам systemctl start.
            timeout = SUDO_START_TIMEOUT
        else:
            if action == "disable_all":
                timeout = 600.0
            elif action in {"install", "rollback"}:
                timeout = 300.0
            else:
                timeout = 240.0
        logger.info("Запуск root-worker службы: %s", action)

        try:
            completed = subprocess.run(
                command,
                input=json.dumps(plan, ensure_ascii=False) + "\n",
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=timeout,
                check=False,
                cwd=PROJECT_ROOT,
            )
        except subprocess.TimeoutExpired:
            return ServiceResult(
                False,
                action,
                f"Операция службы не завершилась за {timeout:g} с.",
            )
        except OSError as exc:
            return ServiceResult(
                False,
                action,
                f"Не удалось запустить sudo -n: {exc}. " + SUDO_HINT,
            )

        result = _parse_worker_result(completed.stdout)
        if result is not None:
            return result

        stderr = _truncate(completed.stderr or "")
        if _sudo_auth_failed(stderr) or completed.returncode in (126, 127):
            message = SUDO_HINT
        else:
            message = (
                "root-worker службы завершился без результата "
                f"(код {completed.returncode})."
            )
        if stderr:
            message += f"\n{stderr}"
        return ServiceResult(
            False,
            action,
            message,
            output=stderr,
            returncode=completed.returncode,
        )


def _parse_worker_result(stdout: str) -> ServiceResult | None:
    for line in reversed(stdout.splitlines()):
        line = line.strip()
        if not line:
            continue
        try:
            data = json.loads(line)
        except ValueError:
            continue
        if not isinstance(data, dict) or "ok" not in data:
            continue
        return ServiceResult(
            ok=bool(data.get("ok")),
            action=str(data.get("action", "service")),
            message=str(data.get("message", "")),
            output=str(data.get("output", "")),
            returncode=data.get("returncode")
            if isinstance(data.get("returncode"), int)
            else None,
        )
    return None


