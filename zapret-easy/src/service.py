def build_nfqws2_args(
    user_name: str,
    strategy_args: tuple[str, ...],
    *,
    lua_dir: Path = ZAPRET_LUA_DIR,
    strategy_copy: Path = STRATEGY_COPY,
) -> list[str]:
    """Собирает полный набор аргументов для nfqws2 @active.conf."""
    args = [
        f"--qnum={SERVICE_QUEUE}",
        f"--fwmark=0x{SERVICE_FWMARK:X}",
        f"--user={user_name}",
    ]
    for name in LUA_INIT_FILES:
        args.append(f"--lua-init=@{lua_dir / name}")
    args.append(f"--lua-init=@{strategy_copy}")
    args.extend(strategy_args)
    return args


def build_active_conf(
    user_name: str,
    strategy_args: tuple[str, ...],
    *,
    lua_dir: Path = ZAPRET_LUA_DIR,
    strategy_copy: Path = STRATEGY_COPY,
) -> str:
    """nfqws2 @file: одна строка, без комментариев, shell-safe quoting."""
    args = build_nfqws2_args(
        user_name,
        strategy_args,
        lua_dir=lua_dir,
        strategy_copy=strategy_copy,
    )
    return shlex.join(args) + "\n"


def _validate_nfqws2_config(
    nfqws2: Path,
    user_name: str,
    strategy_args: tuple[str, ...],
    lua_path: Path,
) -> None:
    """Проверяет кандидат конфигурации через ``nfqws2 --dry-run``.

    ``nfqws2 @file`` принимает файл только единственным аргументом, поэтому
    ``--dry-run`` ставится первым токеном во временном конфиге.  Проверка
    идёт до записи ``active.conf``: при ошибке старый конфиг остаётся на
    месте, а служба не перезапускается.
    """
    if os.geteuid() != 0:
        # --user требует root для initgroups; root-worker вызывает _install
        # уже с euid 0.  Прямой пользовательский вызов всё равно не сможет
        # перезапустить systemd, поэтому не маскируем его другой ошибкой.
        logger.debug("Пропускаю dry-run nfqws2: требуется root для --user")
        return

    strategy_data = _read_strategy(lua_path)

    try:
        temp_dir = Path(
            tempfile.mkdtemp(
                prefix=".nfqws2-dry-run-",
                dir=STATE_DIR,
            )
        )
    except OSError as exc:
        raise ServiceError(
            f"Не удалось подготовить dry-run конфигурации nfqws2: {exc}"
        ) from exc

    try:
        os.chmod(temp_dir, 0o711)
        strategy_path = temp_dir / "strategy.lua"
        strategy_path.write_bytes(strategy_data)
        os.chmod(strategy_path, 0o644)

        candidate = build_active_conf(
            user_name,
            strategy_args,
            strategy_copy=strategy_path,
        )
        candidate_path = temp_dir / "active.conf"
        candidate_path.write_text(
            "--dry-run\n" + candidate,
            encoding="utf-8",
        )
        os.chmod(candidate_path, 0o600)

        try:
            completed = _run(
                [str(nfqws2), f"@{candidate_path}"],
                timeout=30.0,
            )
        except ServiceError as exc:
            logger.error("nfqws2 --dry-run не выполнен: %s", exc)
            raise ServiceError(
                "Не удалось проверить конфигурацию nfqws2 через --dry-run: "
                f"{exc}. Служба не перезапущена."
            ) from exc
        if completed.returncode != 0:
            details = _command_output(completed)
            logger.error(
                "nfqws2 --dry-run отклонил конфигурацию (код %s): %s",
                completed.returncode,
                details,
            )
            raise ServiceError(
                "Новая конфигурация nfqws2 не прошла проверку --dry-run. "
                "Служба не перезапущена, старый конфиг продолжает работать."
                + (f"\n{details}" if details else ""),
                output=details,
            )
        logger.info("nfqws2 --dry-run: конфигурация корректна")
    except OSError as exc:
        logger.error("Не удалось выполнить dry-run nfqws2: %s", exc)
        raise ServiceError(
            "Не удалось проверить конфигурацию nfqws2 через --dry-run: "
            f"{exc}. Служба не перезапущена."
        ) from exc
    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)


