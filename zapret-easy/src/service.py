"""Управление systemd-службой zapret-easy.

TUI работает от обычного пользователя. Все действия, меняющие систему
(запись ``/var/lib/zapret-easy`` и ``/etc/systemd/system``, запуск
``systemctl``, снятие/восстановление nftables), выполняет отдельный
root-worker через ``sudo -n``.

Служба запускает ``nfqws2 @/var/lib/zapret-easy/active.conf``.  Правила
nftables создаёт и удаляет сам zapret2 через ``start_fw`` / ``stop_fw``;
zapret-easy не пишет собственных правил.  Перед первым запуском сохраняется
полный ``nft list ruleset`` (только как аварийная страховка) и отдельный
снимок таблицы ``inet zapret2``.  При штатном откате используется
``stop_fw`` и восстанавливается/удаляется только эта таблица.
"""

