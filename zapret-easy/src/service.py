class ServiceError(Exception):
    """Ошибка установки, управления или отката службы."""

    def __init__(self, message: str, *, output: str = "") -> None:
        super().__init__(message)
        self.output = output


@dataclass(frozen=True, slots=True)
class ServiceStatus:
    """Снимок состояния службы и пакетного zapret2.service."""

    installed: bool
    ours: bool
    active: bool
    enabled: bool
    unit_path: Path
    active_state: str
    enabled_state: str
    package_active: bool
    package_enabled: bool
    detail: str

    @property
    def package_conflict(self) -> bool:
        return self.package_active or self.package_enabled


@dataclass(frozen=True, slots=True)
class ServicePreflight:
    """Проверка перед установкой/запуском службы."""

    errors: tuple[str, ...]
    warnings: tuple[str, ...]
    status: ServiceStatus
    user: str | None
    strategy_name: str | None
    strategy_lua: Path | None
    strategies_dir: Path | None
    strategy_args: tuple[str, ...]
    nfqws2: Path | None
    ports_tcp: str
    ports_udp: str

    @property
    def ok(self) -> bool:
        return not self.errors


@dataclass(frozen=True, slots=True)
class ServiceResult:
    """Результат root-операции."""

    ok: bool
    action: str
    message: str
    output: str = ""
    returncode: int | None = None


