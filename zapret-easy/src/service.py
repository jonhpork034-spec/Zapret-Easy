def _sudo_auth_failed(text: str | None) -> bool:
    value = (text or "").lower()
    return any(
        marker in value
        for marker in (
            "password is required",
            "a terminal is required",
            "no tty present",
            "askpass",
            "not allowed to execute",
        )
    )


def _truncate(text: str, limit: int = 4000) -> str:
    text = text.strip()
    if len(text) <= limit:
        return text
    return "…\n" + text[-limit:]


def _command_output(completed: subprocess.CompletedProcess[str]) -> str:
    return _truncate(completed.stderr or completed.stdout or "")


def _tool(name: str) -> Path | None:
    """Возвращает абсолютный путь к исполняемому файлу."""
    raw = shutil.which(name)
    if not raw:
        return None
    path = Path(raw)
    try:
        path = path.resolve(strict=True)
    except OSError:
        return None
    if not path.is_file() or not os.access(path, os.X_OK):
        return None
    return path


def _base_env() -> dict[str, str]:
    env = os.environ.copy()
    env["PATH"] = _SYSTEM_PATH
    env["LC_ALL"] = "C"
    env["SYSTEMD_PAGER"] = "cat"
    env["NO_COLOR"] = "1"
    return env


def _run(
    argv: list[str] | tuple[str, ...],
    *,
    timeout: float,
    input_text: str | None = None,
) -> subprocess.CompletedProcess[str]:
    if not argv:
        raise ServiceError("Пустая команда.")
    first = Path(argv[0])
    if not first.is_absolute():
        raise ServiceError(f"Команда должна запускаться по абсолютному пути: {argv[0]}")
    try:
        return subprocess.run(
            list(argv),
            input=input_text,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
            check=False,
            env=_base_env(),
        )
    except subprocess.TimeoutExpired as exc:
        raise ServiceError(
            f"Команда не завершилась за {timeout:g} с: {argv[0]}"
        ) from exc
    except OSError as exc:
        raise ServiceError(f"Не удалось запустить {argv[0]}: {exc}") from exc


def _systemctl_optional(
    systemctl: Path,
    *args: str,
    timeout: float = 8.0,
) -> subprocess.CompletedProcess[str] | None:
    try:
        return _run(
            [str(systemctl), *args],
            timeout=timeout,
        )
    except ServiceError:
        return None


def _systemctl_required(
    systemctl: Path,
    *args: str,
    timeout: float = 30.0,
) -> subprocess.CompletedProcess[str]:
    completed = _run([str(systemctl), *args], timeout=timeout)
    if completed.returncode != 0:
        details = _command_output(completed)
        raise ServiceError(
            f"systemctl {' '.join(args)} завершился с кодом "
            f"{completed.returncode}."
            + (f"\n{details}" if details else ""),
            output=details,
        )
    return completed


def _systemctl_state(systemctl: Path | None, verb: str, unit: str) -> str:
    if systemctl is None:
        return "unknown"
    completed = _systemctl_optional(systemctl, verb, unit, timeout=4.0)
    if completed is None:
        return "unknown"
    lines = completed.stdout.strip().splitlines()
    if not lines:
        return "unknown"
    return lines[0].strip() or "unknown"


