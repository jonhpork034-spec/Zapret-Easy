def _ensure_root() -> None:
    if os.geteuid() != 0:
        raise ServiceError("Root-worker службы должен запускаться через sudo -n.")


def _ensure_no_package_conflict(systemctl: Path) -> None:
    active = _systemctl_state(systemctl, "is-active", PACKAGE_SERVICE)
    if active == "active":
        raise ServiceError(
            "Служба zapret2.service активна. Остановите и отключите её: "
            "systemctl disable --now zapret2.service"
        )
    enabled = _systemctl_state(systemctl, "is-enabled", PACKAGE_SERVICE)
    if enabled in {"enabled", "enabled-runtime"}:
        raise ServiceError(
            "Служба zapret2.service включена и запустится при загрузке. "
            "Отключите её: systemctl disable --now zapret2.service"
        )


def _install(
    plan: _InstallPlan,
    *,
    systemctl: Path,
    nft: Path,
) -> ServiceResult:
    _ensure_no_package_conflict(systemctl)
    if _systemctl_state(systemctl, "is-enabled", SERVICE_NAME) == "masked":
        raise ServiceError(
            f"{SERVICE_NAME} замаскирована. Снимите маску: "
            f"systemctl unmask {SERVICE_NAME}"
        )
    _ensure_unit_manageable()
    _ensure_state_dir()

    nfqws2 = _find_nfqws2()
    if nfqws2 is None:
        raise ServiceError("nfqws2 не найден. Установите пакет zapret2.")

    for name in LUA_INIT_FILES:
        path = ZAPRET_LUA_DIR / name
        if not path.is_file():
            raise ServiceError(f"Не найдена Lua-библиотека zapret2: {path}")

    if not ZAPRET_INIT.is_file() or not os.access(ZAPRET_INIT, os.X_OK):
        raise ServiceError(f"Не найден исполняемый init-скрипт: {ZAPRET_INIT}")

    source = _choose_zapret_config_source()
    _validate_nfqws2_config(
        nfqws2,
        plan.user_name,
        plan.args,
        plan.lua_path,
    )
    _copy_strategy(plan.lua_path)
    _atomic_write_text(
        ACTIVE_CONF,
        build_active_conf(plan.user_name, plan.args),
        0o600,
    )
    _atomic_write_text(
        ZAPRET_CONF,
        build_zapret2_conf(
            plan.user_name,
            plan.ports_tcp,
            plan.ports_udp,
            source,
        ),
        0o600,
    )
    _atomic_write_text(
        FIREWALL_SCRIPT,
        build_firewall_script(nft),
        0o700,
    )
    _atomic_write_text(
        UNIT_PATH,
        build_unit(
            nfqws2=nfqws2,
            user_name=plan.user_name,
            user_home=plan.user_home,
            strategy_name=plan.strategy_name,
        ),
        0o644,
    )
    _atomic_write_text(
        META_FILE,
        json.dumps(
            {
                "strategy": plan.strategy_name,
                "user": plan.user_name,
                "nfqws2": str(nfqws2),
                "ports_tcp": plan.ports_tcp,
                "ports_udp": plan.ports_udp,
            },
            ensure_ascii=False,
            indent=2,
        )
        + "\n",
        0o600,
    )

    _systemctl_required(systemctl, "daemon-reload", timeout=30.0)
    _systemctl_optional(systemctl, "reset-failed", SERVICE_NAME, timeout=10.0)
    _systemctl_required(systemctl, "enable", SERVICE_NAME, timeout=30.0)
    _systemctl_required(systemctl, "restart", SERVICE_NAME, timeout=150.0)
    _assert_service_active(systemctl)

    return ServiceResult(
        True,
        "install",
        f"Служба {SERVICE_NAME} установлена и запущена. "
        f"Стратегия: {plan.strategy_name}.",
    )


def _assert_service_active(systemctl: Path) -> None:
    # Type=simple считается запущенным сразу после fork, а Restart=on-failure
    # может на секунды оставить состояние activating.  Ждём ограниченное
    # время и прикладываем status/journal, чтобы видеть LUA ERROR nfqws2,
    # а не только бесполезное «activating».
    state = "unknown"
    deadline = time.monotonic() + 5.0
    while time.monotonic() < deadline:
        state = _systemctl_state(systemctl, "is-active", SERVICE_NAME)
        if state == "active":
            return
        time.sleep(0.25)

    status = _systemctl_optional(
        systemctl,
        "status",
        SERVICE_NAME,
        "--no-pager",
        "-l",
        timeout=10.0,
    )
    details = _command_output(status) if status is not None else ""
    raise ServiceError(
        f"Служба не активна после запуска (состояние: {state})."
        + (f"\n{details}" if details else ""),
        output=details,
    )


def _start(*, systemctl: Path) -> ServiceResult:
    _ensure_no_package_conflict(systemctl)
    if not UNIT_PATH.is_file():
        raise ServiceError(
            "Служба не установлена. Сначала выполните установку zapret-easy."
        )
    if not _unit_is_ours():
        raise ServiceError(f"{UNIT_PATH} создан не zapret-easy.")
    _systemctl_optional(systemctl, "reset-failed", SERVICE_NAME, timeout=10.0)
    _systemctl_required(
        systemctl,
        "--no-ask-password",
        "start",
        SERVICE_NAME,
        timeout=START_TIMEOUT,
    )
    _assert_service_active(systemctl)
    return ServiceResult(True, "start", f"Служба {SERVICE_NAME} запущена.")


def _stop(*, systemctl: Path | None) -> ServiceResult:
    if UNIT_PATH.exists() and not _unit_is_ours():
        raise ServiceError(
            f"{UNIT_PATH} создан не zapret-easy; останавливать чужую "
            "службу запрещено."
        )
    if systemctl is None:
        if UNIT_PATH.exists():
            raise ServiceError(
                "systemctl не найден: нельзя гарантированно остановить службу."
            )
    else:
        completed = _systemctl_optional(
            systemctl,
            "stop",
            SERVICE_NAME,
            timeout=45.0,
        )
        state_after_stop = _systemctl_state(
            systemctl,
            "is-active",
            SERVICE_NAME,
        )
        if state_after_stop not in {"inactive", "failed"}:
            details = (
                _command_output(completed)
                if completed is not None
                else ""
            )
            raise ServiceError(
                "Не удалось подтвердить остановку службы "
                f"(состояние: {state_after_stop})."
                + (f"\n{details}" if details else ""),
                output=details,
            )
        if completed is None and UNIT_PATH.exists():
            raise ServiceError("Не удалось выполнить systemctl stop.")
        if (
            completed is not None
            and completed.returncode != 0
            and UNIT_PATH.exists()
        ):
            details = _command_output(completed)
            raise ServiceError(
                f"systemctl stop завершился с кодом {completed.returncode}."
                + (f"\n{details}" if details else ""),
                output=details,
            )
    if FIREWALL_SCRIPT.is_file():
        _run_firewall("down")
    elif NFT_TABLE_STATE.exists() or NFT_TABLE_OWNED.exists():
        raise ServiceError(
            f"Не найден firewall-helper {FIREWALL_SCRIPT}; правила inet "
            f"{NFT_TABLE} могли остаться. Выполните откат вручную."
        )
    return ServiceResult(True, "stop", f"Служба {SERVICE_NAME} остановлена.")


def _unit_loaded(systemctl: Path, unit: str) -> bool:
    completed = _systemctl_optional(
        systemctl,
        "show",
        "-p",
        "LoadState",
        "--value",
        unit,
        timeout=5.0,
    )
    if completed is None:
        return False
    return completed.stdout.strip() == "loaded"


def _disable_all(*, systemctl: Path) -> ServiceResult:
    """Останавливает и отключает zapret-easy, zapret2, zapret и таймеры."""
    units = [unit for unit in ZAPRET_UNITS if _unit_loaded(systemctl, unit)]
    if not units:
        return ServiceResult(
            True,
            "disable_all",
            "Службы zapret не найдены — выключать нечего.",
        )

    errors: list[str] = []
    warnings: list[str] = []
    for unit in units:
        stop_result = _systemctl_optional(
            systemctl,
            "stop",
            unit,
            timeout=60.0,
        )
        if stop_result is None:
            errors.append(f"{unit}: systemctl stop не ответил")
        elif stop_result.returncode != 0:
            details = _command_output(stop_result)
            errors.append(
                f"{unit}: stop завершился с кодом {stop_result.returncode}"
                + (f" ({details})" if details else "")
            )

        disable_result = _systemctl_optional(
            systemctl,
            "disable",
            unit,
            timeout=30.0,
        )
        if disable_result is None:
            errors.append(f"{unit}: systemctl disable не ответил")
        elif disable_result.returncode != 0:
            details = _command_output(disable_result)
            warnings.append(
                f"{unit}: disable не выполнен"
                + (f" ({details})" if details else "")
            )

    _systemctl_optional(
        systemctl,
        "reset-failed",
        *units,
        timeout=15.0,
    )

    still_active: list[str] = []
    still_enabled: list[str] = []
    for unit in units:
        active_state = _systemctl_state(systemctl, "is-active", unit)
        if active_state in {
            "active",
            "activating",
            "reloading",
            "deactivating",
        }:
            still_active.append(f"{unit} ({active_state})")
        enabled_state = _systemctl_state(systemctl, "is-enabled", unit)
        if enabled_state in {"enabled", "enabled-runtime"}:
            still_enabled.append(unit)

    if still_active:
        errors.append("остались активными: " + ", ".join(still_active))
    if still_enabled:
        errors.append("остались включёнными: " + ", ".join(still_enabled))

    if errors:
        message = (
            "Не удалось полностью выключить службы zapret:\n- "
            + "\n- ".join(errors)
        )
        if warnings:
            message += "\n\nПредупреждения:\n- " + "\n- ".join(warnings)
        return ServiceResult(False, "disable_all", message)

    message = (
        "Остановлены и отключены: "
        + ", ".join(units)
        + ". Обход DPI выключен до ручного включения."
    )
    if warnings:
        message += "\n\nПредупреждения:\n- " + "\n- ".join(warnings)
    return ServiceResult(True, "disable_all", message)


def _remove_generated_files() -> None:
    for path in (
        ACTIVE_CONF,
        ZAPRET_CONF,
        STRATEGY_COPY,
        FIREWALL_SCRIPT,
        META_FILE,
        NFT_TABLE_STATE,
        NFT_TABLE_OWNED,
        NFT_TABLE_BACKUP,
        NFT_BACKUP_DONE,
        Path(f"{NFT_FULL_BACKUP}.tmp"),
        Path(f"{NFT_TABLE_BACKUP}.tmp"),
    ):
        with contextlib.suppress(OSError):
            path.unlink(missing_ok=True)


def _rollback(*, systemctl: Path | None) -> ServiceResult:
    warnings: list[str] = []

    if UNIT_PATH.exists() and not _unit_is_ours():
        raise ServiceError(
            f"{UNIT_PATH} создан не zapret-easy. Откат запрещён: "
            "удалите сторонний unit-файл вручную."
        )

    if systemctl is not None:
        package_state = _systemctl_state(
            systemctl,
            "is-active",
            PACKAGE_SERVICE,
        )
        if package_state not in {"inactive", "failed", "unknown"}:
            raise ServiceError(
                f"Служба {PACKAGE_SERVICE} находится в состоянии "
                f"{package_state}. Остановите её перед откатом: иначе "
                "можно перезаписать таблицу inet zapret2, которой она "
                "пользуется."
            )

    if systemctl is None:
        if UNIT_PATH.exists():
            raise ServiceError(
                "systemctl не найден: нельзя гарантированно остановить службу. "
                "Откат прерван."
            )
    else:
        stop_result = _systemctl_optional(
            systemctl,
            "stop",
            SERVICE_NAME,
            timeout=45.0,
        )
        state_after_stop = _systemctl_state(
            systemctl,
            "is-active",
            SERVICE_NAME,
        )
        if state_after_stop == "active" or (
            UNIT_PATH.exists()
            and state_after_stop not in {"inactive", "failed"}
        ):
            details = (
                _command_output(stop_result)
                if stop_result is not None
                else ""
            )
            raise ServiceError(
                "Не удалось подтвердить остановку службы после "
                "systemctl stop. Откат прерван, unit-файл не удалён."
                + (f"\n{details}" if details else ""),
                output=details,
            )
        if stop_result is not None and stop_result.returncode != 0:
            warnings.append(
                "systemctl stop завершился с ошибкой, но служба не активна"
            )
        disable_result = _systemctl_optional(
            systemctl,
            "disable",
            SERVICE_NAME,
            timeout=30.0,
        )
        if disable_result is not None and disable_result.returncode != 0:
            warnings.append("systemctl disable завершился с ошибкой")

    for path in (UNIT_PATH, UNIT_WANTS_PATH):
        try:
            path.unlink(missing_ok=True)
        except OSError as exc:
            warnings.append(f"не удалось удалить {path}: {exc}")

    if systemctl is not None:
        reload_result = _systemctl_optional(
            systemctl,
            "daemon-reload",
            timeout=30.0,
        )
        if reload_result is None or reload_result.returncode != 0:
            warnings.append("systemctl daemon-reload завершился с ошибкой")
        _systemctl_optional(
            systemctl,
            "reset-failed",
            SERVICE_NAME,
            timeout=10.0,
        )

    restore_error: ServiceError | None = None
    if FIREWALL_SCRIPT.is_file():
        try:
            _run_firewall("restore")
        except ServiceError as exc:
            restore_error = exc
    elif NFT_TABLE_STATE.exists() or NFT_TABLE_OWNED.exists():
        restore_error = ServiceError(
            "Не найден firewall-helper; снимок inet zapret2 не восстановлен."
        )

    if restore_error is not None:
        message = (
            f"Служба {SERVICE_NAME} удалена, но nftables не восстановлен:\n"
            f"{restore_error}"
        )
        if warnings:
            message += "\n\nПредупреждения:\n" + "\n".join(warnings)
        return ServiceResult(
            False,
            "rollback",
            message,
            output=restore_error.output,
        )

    _remove_generated_files()
    message = (
        f"Служба {SERVICE_NAME} удалена, unit-файл и wants-ссылка удалены, "
        "daemon-reload выполнен, таблица inet zapret2 восстановлена/удалена."
    )
    if warnings:
        message += "\n\nПредупреждения:\n" + "\n".join(warnings)
    return ServiceResult(True, "rollback", message)


def _run_firewall(action: str) -> None:
    if not FIREWALL_SCRIPT.is_file():
        raise ServiceError(f"Не найден firewall-helper: {FIREWALL_SCRIPT}")
    if not os.access(FIREWALL_SCRIPT, os.X_OK):
        raise ServiceError(f"{FIREWALL_SCRIPT} не исполняемый.")
    completed = _run([str(FIREWALL_SCRIPT), action], timeout=90.0)
    if completed.returncode != 0:
        details = _command_output(completed)
        raise ServiceError(
            f"firewall-helper {action} завершился с кодом "
            f"{completed.returncode}."
            + (f"\n{details}" if details else ""),
            output=details,
        )


def _execute_plan(
    action: str,
    install_plan: _InstallPlan | None,
) -> ServiceResult:
    systemctl = _tool("systemctl")
    if systemctl is None:
        raise ServiceError("systemctl не найден.")
    nft = _tool("nft")

    if action == "install":
        if install_plan is None:
            raise ServiceError("Не передан план установки.")
        if nft is None:
            raise ServiceError("nft не найден. Установите nftables.")
        return _install(install_plan, systemctl=systemctl, nft=nft)

    if action == "start":
        return _start(systemctl=systemctl)

    if action == "stop":
        return _stop(systemctl=systemctl)

    if action == "disable_all":
        return _disable_all(systemctl=systemctl)

    if action == "rollback":
        return _rollback(systemctl=systemctl)

    raise ServiceError(f"Неизвестное действие: {action}")


def _emit_result(result: ServiceResult) -> None:
    sys.stdout.write(
        json.dumps(asdict(result), ensure_ascii=False) + "\n"
    )
    sys.stdout.flush()


def worker_main() -> int:
    """Точка входа root-worker-а. План читается одной JSON-строкой из stdin."""
    action = "service"
    try:
        _ensure_root()
        raw = sys.stdin.buffer.readline(MAX_WORKER_LINE + 1)
        if not raw:
            raise ServiceError("Не получен план операции службы.")
        if len(raw) > MAX_WORKER_LINE:
            raise ServiceError("План операции службы слишком большой.")
        try:
            data = json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, ValueError) as exc:
            raise ServiceError(f"Некорректный JSON плана службы: {exc}") from exc
        action, install_plan = _validate_plan(data)
        result = _execute_plan(action, install_plan)
    except ServiceError as exc:
        result = ServiceResult(
            False,
            action,
            str(exc),
            output=exc.output,
        )
    except Exception as exc:  # noqa: BLE001 - worker всегда отдаёт JSON
        logger.exception("Непредвиденная ошибка root-worker службы")
        result = ServiceResult(
            False,
            action,
            f"{type(exc).__name__}: {exc}",
        )

    _emit_result(result)
    return 0 if result.ok else 1


