def main(argv: list[str] | None = None) -> int:
    if "--worker" in sys.argv[1:]:
        return worker_main()

    parser = argparse.ArgumentParser(
        description="Проверка и управление службой zapret-easy."
    )
    parser.add_argument(
        "--status",
        action="store_true",
        help="показать состояние службы",
    )
    parser.add_argument(
        "--preflight",
        action="store_true",
        help="проверить готовность к установке службы",
    )
    args = parser.parse_args(argv)
    service = ServiceManager()

    if args.preflight:
        preflight = service.preflight()
        for error in preflight.errors:
            print(f"ОШИБКА: {error}")
        for warning in preflight.warnings:
            print(f"ВНИМАНИЕ: {warning}")
        return 0 if preflight.ok else 1

    status = service.status()
    print(f"Unit:       {status.unit_path}")
    print(f"Установлена: {'да' if status.installed else 'нет'}")
    print(f"Наша:       {'да' if status.ours else 'нет'}")
    print(f"Активна:    {status.active_state}")
    print(f"Включена:   {status.enabled_state}")
    print(f"zapret2:    active={status.package_active} "
          f"enabled={status.package_enabled}")
    print(f"Состояние:  {status.detail}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
