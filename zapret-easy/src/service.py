def build_firewall_script(nft: Path) -> str:
    """Генерирует root-helper для ExecStartPre/ExecStopPost."""
    q = shlex.quote
    return f"""#!/bin/sh
# Generated by zapret-easy. Do not edit.
set -eu
umask 077
PATH={q(_SYSTEM_PATH)}
STATE_DIR={q(str(STATE_DIR))}
ZAPRET_BASE={q(str(ZAPRET_BASE))}
ZAPRET_RW={q(str(ZAPRET_BASE))}
ZAPRET_CONFIG={q(str(ZAPRET_CONF))}
ZAPRET_INIT={q(str(ZAPRET_INIT))}
NFT={q(str(nft))}
TABLE={q(NFT_TABLE)}
FULL_BACKUP={q(str(NFT_FULL_BACKUP))}
TABLE_BACKUP={q(str(NFT_TABLE_BACKUP))}
TABLE_STATE={q(str(NFT_TABLE_STATE))}
TABLE_OWNED={q(str(NFT_TABLE_OWNED))}
BACKUP_DONE={q(str(NFT_BACKUP_DONE))}

log() {{
    printf 'zapret-easy firewall: %s\\n' "$*" >&2
}}

backup_once()
{{
    if [ ! -e "$BACKUP_DONE" ]; then
        tmp="$FULL_BACKUP.tmp"
        if ! "$NFT" list ruleset >"$tmp"; then
            rm -f "$tmp"
            log "не удалось сохранить полный nftables backup"
            return 1
        fi
        mv -f "$tmp" "$FULL_BACKUP"
        : >"$BACKUP_DONE"
    fi

    if [ ! -e "$TABLE_STATE" ]; then
        if "$NFT" list table inet "$TABLE" >/dev/null 2>&1; then
            tmp="$TABLE_BACKUP.tmp"
            if ! "$NFT" list table inet "$TABLE" >"$tmp"; then
                rm -f "$tmp"
                log "не удалось сохранить снимок inet $TABLE"
                return 1
            fi
            mv -f "$tmp" "$TABLE_BACKUP"
            printf 'present\\n' >"$TABLE_STATE"
        else
            printf 'absent\\n' >"$TABLE_STATE"
        fi
    fi

    if [ "$(cat "$TABLE_STATE" 2>/dev/null || printf 'absent')" = "present" ] \
        && [ ! -s "$TABLE_BACKUP" ]; then
        log "снимок inet $TABLE потерян; запуск без возможности отката запрещён"
        return 1
    fi
    return 0
}}

clean_table()
{{
    if [ ! -x "$NFT" ]; then
        log "не найден исполняемый nft: $NFT"
        return 1
    fi
    if "$NFT" delete table inet "$TABLE" >/dev/null 2>&1; then
        return 0
    fi
    if "$NFT" list table inet "$TABLE" >/dev/null 2>&1; then
        return 1
    fi
    return 0
}}

run_init()
{{
    ZAPRET_BASE="$ZAPRET_BASE" \\
    ZAPRET_RW="$ZAPRET_RW" \\
    ZAPRET_CONFIG="$ZAPRET_CONFIG" \\
    "$ZAPRET_INIT" "$1"
}}

down()
{{
    # Без отметки владения мы не знаем, кому принадлежит таблица.
    # Не трогаем её: иначе неудачный ExecStartPre может удалить чужие правила.
    if [ ! -e "$TABLE_OWNED" ]; then
        log "нет отметки владения inet $TABLE; таблица не изменяется"
        return 0
    fi
    if [ -x "$ZAPRET_INIT" ]; then
        run_init stop_fw >/dev/null 2>&1 || true
    fi
    if ! clean_table; then
        log "не удалось удалить таблицу inet $TABLE"
        return 1
    fi
    rm -f "$TABLE_OWNED"
    return 0
}}

case "${{1:-}}" in
    up)
        if [ ! -x "$ZAPRET_INIT" ]; then
            log "не найден исполняемый $ZAPRET_INIT"
            exit 1
        fi
        if command -v systemctl >/dev/null 2>&1; then
            package_state=$(systemctl is-active zapret2.service 2>/dev/null || true)
            case "$package_state" in
                active|activating|reloading|deactivating)
                    log "zapret2.service уже активна; второй nfqws2 запрещён"
                    exit 1
                    ;;
            esac
            package_enabled=$(systemctl is-enabled zapret2.service 2>/dev/null || true)
            case "$package_enabled" in
                enabled|enabled-runtime)
                    log "zapret2.service включена; сначала отключите её"
                    exit 1
                    ;;
            esac
        fi
        backup_once || exit 1
        clean_table || exit 1
        : >"$TABLE_OWNED" || exit 1
        run_init start_fw || exit 1
        if ! "$NFT" list table inet "$TABLE" >/dev/null 2>&1; then
            log "после start_fw таблица inet $TABLE не создана"
            exit 1
        fi
        ;;
    down)
        down || exit 1
        ;;
    restore)
        state=$(cat "$TABLE_STATE" 2>/dev/null || printf '')
        if [ -z "$state" ]; then
            if [ -e "$TABLE_OWNED" ]; then
                log "снимок inet $TABLE потерян; удаляю нашу таблицу"
                clean_table || exit 1
                rm -f "$TABLE_OWNED" || exit 1
            else
                log "нет снимка inet $TABLE; таблица не изменяется"
            fi
            exit 0
        fi
        if [ "$state" = "present" ] && [ ! -s "$TABLE_BACKUP" ]; then
            log "снимок inet $TABLE отсутствует; таблица не изменяется"
            exit 1
        fi
        if [ "$state" != "present" ] && [ "$state" != "absent" ]; then
            log "неизвестное состояние снимка inet $TABLE: $state"
            exit 1
        fi
        if [ -e "$TABLE_OWNED" ]; then
            down || exit 1
        else
            # up не успел пометить владение, но снимок уже есть.
            # Удаляем текущую таблицу и восстанавливаем исходную.
            clean_table || exit 1
        fi
        if [ "$state" = "present" ]; then
            "$NFT" -f "$TABLE_BACKUP" || exit 1
        fi
        rm -f "$TABLE_STATE" "$TABLE_BACKUP" "$TABLE_OWNED" || exit 1
        ;;
    *)
        echo "Использование: $0 {{up|down|restore}}" >&2
        exit 2
        ;;
esac
exit 0
"""


def _systemd_env_value(value: str) -> str:
    if re.search(r'[\s"\\]', value):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    return value


def _unit_description(strategy_name: str) -> str:
    safe = "".join(
        char
        for char in strategy_name
        if char.isprintable() and char not in "\r\n"
    )
    return safe.replace("%", "%%") or "nfqws2"


