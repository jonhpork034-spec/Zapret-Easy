"""Безопасные сетевые sysctl-твики для zapret-easy.

Модуль меняет только небольшой набор проверенных параметров через
``/etc/sysctl.d/99-zapret-easy.conf``.  Ядро, загрузчик, nftables и
systemd-юниты не затрагиваются.  Запись в /etc выполняет root-worker,
запускаемый из TUI через ``pkexec``.

Перед первым применением сохраняются:

* существующий ``99-zapret-easy.conf``;
* текущие значения всех затрагиваемых ключей в
  ``/var/lib/zapret-easy/tweaks/before.json``.

После записи выполняется ``sysctl -p`` и проверка фактических значений.
Если проверка не прошла, старые значения и файл восстанавливаются.
"""

from __future__ import annotations

import json
import logging
import os
import shutil
import subprocess
import sys
import tempfile
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Final

logger = logging.getLogger("zapret-easy.tweaks")

PROJECT_ROOT: Final = Path(__file__).resolve().parent.parent
SYSCTL_FILE: Final = Path("/etc/sysctl.d/99-zapret-easy.conf")
BACKUP_DIR: Final = Path("/var/lib/zapret-easy/tweaks")
BEFORE_FILE: Final = BACKUP_DIR / "before.json"
MAX_WORKER_LINE: Final = 64 * 1024
SYSCTL_TIMEOUT: Final = 30.0
SYSTEM_PATH: Final = (
    "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
)

_FILE_MARKER: Final = "# Generated by zapret-easy. Do not edit; use the TUI."

# sysctl-ключ -> путь относительно /proc/sys
SYSCTL_KEYS: Final = {
    "net.core.default_qdisc": "net/core/default_qdisc",
    "net.ipv4.tcp_congestion_control": "net/ipv4/tcp_congestion_control",
    "net.core.netdev_max_backlog": "net/core/netdev_max_backlog",
    "net.ipv4.tcp_fastopen": "net/ipv4/tcp_fastopen",
    "net.ipv4.tcp_mtu_probing": "net/ipv4/tcp_mtu_probing",
    "net.ipv4.ip_forward": "net/ipv4/ip_forward",
}

class TweakError(Exception):
    """Ошибка чтения, проверки или применения сетевых твиков."""


@dataclass(frozen=True, slots=True)
class TweakOptions:
    """Выбранные пользователем безопасные sysctl-опции."""

    qdisc: str | None = "auto"
    bbr: bool = True
    netdev_backlog: bool = True
    tcp_fastopen: bool = True
    tcp_mtu_probing: bool = True
    ip_forward: bool = False


@dataclass(frozen=True, slots=True)
class TweakStatus:
    """Состояние твиков, читаемое без root."""

    file_exists: bool
    file_ours: bool
    current: dict[str, str]
    qdiscs: tuple[str, ...]
    bbr_available: bool
    before_file: bool
    backup_file: Path | None


@dataclass(frozen=True, slots=True)
class TweakResult:
    """Результат root-операции."""

    ok: bool
    message: str
    output: str = ""
    returncode: int | None = None


def _base_env() -> dict[str, str]:
    """Минимальное предсказуемое окружение для pkexec-потомка."""
    env = {
        key: value
        for key, value in os.environ.items()
        if key in {"LANG", "LC_ALL", "LC_CTYPE", "TERM", "COLORTERM"}
        or key.startswith("LC_")
    }
    env["PATH"] = SYSTEM_PATH
    env.setdefault("LC_ALL", "C.UTF-8")
    return env


def _run(
    command: list[str],
    *,
    timeout: float = SYSCTL_TIMEOUT,
    input_text: str | None = None,
) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
            cwd=PROJECT_ROOT,
            env=_base_env(),
            input=input_text,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise TweakError(f"Не удалось выполнить {command[0]}: {exc}") from exc


def _command_output(completed: subprocess.CompletedProcess[str]) -> str:
    parts = [completed.stdout.strip(), completed.stderr.strip()]
    return "\n".join(part for part in parts if part)


def _read_values() -> dict[str, str]:
    values: dict[str, str] = {}
    for key, relative in SYSCTL_KEYS.items():
        path = Path("/proc/sys") / relative
        try:
            values[key] = path.read_text(encoding="utf-8").strip()
        except OSError:
            continue
    return values


def _read_file_marker(path: Path | None = None) -> bool:
    target = path if path is not None else SYSCTL_FILE
    try:
        with target.open("rb") as stream:
            head = stream.read(4096)
    except OSError:
        return False
    return head.startswith(_FILE_MARKER.encode("utf-8"))


def _managed_keys() -> set[str]:
    """Ключи, которые прошлый запуск zapret-easy записал в наш файл."""
    if not SYSCTL_FILE.is_file() or not _read_file_marker():
        return set()
    keys: set[str] = set()
    try:
        lines = SYSCTL_FILE.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError):
        return set()
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key = stripped.split("=", 1)[0].strip()
        if key in SYSCTL_KEYS:
            keys.add(key)
    return keys


def _module_present(name: str) -> bool:
    if Path(f"/sys/module/sch_{name}").exists():
        return True
    try:
        release = os.uname().release
    except OSError:
        return False
    directory = Path("/lib/modules") / release / "kernel" / "net" / "sched"
    if not directory.is_dir():
        return False
    for suffix in (".ko", ".ko.xz", ".ko.zst", ".ko.gz"):
        if (directory / f"sch_{name}{suffix}").is_file():
            return True
    return False


def _available_qdiscs() -> tuple[str, ...]:
    # fq — штатный вариант для CachyOS/Arch; cake добавляем только если
    # модуль действительно присутствует, чтобы не получить ошибку sysctl.
    values = ["fq"]
    if _module_present("cake"):
        values.append("cake")
    return tuple(values)


def _bbr_available() -> bool:
    try:
        text = Path(
            "/proc/sys/net/ipv4/tcp_available_congestion_control"
        ).read_text(encoding="utf-8")
    except OSError:
        return False
    return "bbr" in text.split()


def _find_sysctl() -> str:
    found = shutil.which("sysctl")
    if found:
        return found
    for candidate in ("/usr/sbin/sysctl", "/sbin/sysctl", "/usr/bin/sysctl"):
        if os.access(candidate, os.X_OK):
            return candidate
    raise TweakError("sysctl не найден.")


def _write_atomic(path: Path, text: str, mode: int) -> None:
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, temp_name = tempfile.mkstemp(
            prefix=f".{path.name}.",
            suffix=".tmp",
            dir=path.parent,
        )
    except OSError as exc:
        raise TweakError(f"Не удалось подготовить {path}: {exc}") from exc

    temp_path = Path(temp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(text)
            if not text.endswith("\n"):
                stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temp_path, mode)
        os.replace(temp_path, path)
    except OSError as exc:
        temp_path.unlink(missing_ok=True)
        raise TweakError(f"Не удалось записать {path}: {exc}") from exc


def _backup_existing_file() -> Path | None:
    if not SYSCTL_FILE.exists():
        return None
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S-%f")
    try:
        BACKUP_DIR.mkdir(parents=True, exist_ok=True)
        os.chmod(BACKUP_DIR, 0o700)
        backup = BACKUP_DIR / f"99-zapret-easy.conf.{stamp}.bak"
        shutil.copy2(SYSCTL_FILE, backup)
        os.chmod(backup, 0o600)
    except OSError as exc:
        raise TweakError(f"Не удалось сохранить backup sysctl-файла: {exc}") from exc
    return backup


def _load_before() -> dict[str, Any] | None:
    if not BEFORE_FILE.is_file():
        return None
    try:
        data = json.loads(BEFORE_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(data, dict):
        return None
    values = data.get("values")
    if not isinstance(values, dict):
        return None
    return data


def _save_before(
    values: dict[str, str],
    *,
    file_existed: bool,
    file_backup: Path | None,
) -> None:
    if _load_before() is not None:
        return
    payload = {
        "version": 1,
        "created_at": datetime.now(timezone.utc).isoformat(
            timespec="seconds"
        ),
        "values": values,
        "file_existed": file_existed,
        "file_backup": str(file_backup) if file_backup else None,
    }
    try:
        BACKUP_DIR.mkdir(parents=True, exist_ok=True)
        os.chmod(BACKUP_DIR, 0o700)
        _write_atomic(
            BEFORE_FILE,
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            0o600,
        )
    except OSError as exc:
        raise TweakError(f"Не удалось сохранить before.json: {exc}") from exc


def _run_sysctl(
    path: Path,
    *,
    description: str,
) -> subprocess.CompletedProcess[str]:
    sysctl = _find_sysctl()
    completed = _run([sysctl, "-p", str(path)])
    if completed.returncode != 0:
        details = _command_output(completed)
        raise TweakError(
            f"sysctl -p не применил {description}."
            + (f"\n{details}" if details else "")
        )
    return completed


def _apply_values(values: dict[str, str], *, description: str) -> None:
    if not values:
        return
    lines = [
        f"{key} = {value}"
        for key, value in values.items()
        if key in SYSCTL_KEYS and value
    ]
    if not lines:
        return
    parent = SYSCTL_FILE.parent
    try:
        parent.mkdir(parents=True, exist_ok=True)
        fd, temp_name = tempfile.mkstemp(
            prefix=".zapret-easy-revert.",
            suffix=".conf",
            dir=parent,
        )
    except OSError as exc:
        raise TweakError(f"Не удалось подготовить rollback-файл: {exc}") from exc
    path = Path(temp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write("\n".join(lines) + "\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(path, 0o600)
        _run_sysctl(path, description=description)
    finally:
        path.unlink(missing_ok=True)


def _restore_file(before: dict[str, Any]) -> None:
    backup_value = before.get("file_backup")
    file_existed = bool(before.get("file_existed"))
    if isinstance(backup_value, str) and backup_value:
        backup = Path(backup_value)
        if backup.is_file():
            try:
                shutil.copy2(backup, SYSCTL_FILE)
                os.chmod(SYSCTL_FILE, 0o644)
                return
            except OSError as exc:
                raise TweakError(
                    f"Не удалось восстановить {SYSCTL_FILE}: {exc}"
                ) from exc
    if file_existed:
        raise TweakError(
            "Не найден backup исходного sysctl-файла; "
            "восстановление невозможно."
        )
    try:
        SYSCTL_FILE.unlink(missing_ok=True)
    except OSError as exc:
        raise TweakError(
            f"Не удалось удалить {SYSCTL_FILE}: {exc}"
        ) from exc


def _build_lines(
    options: TweakOptions,
    current: dict[str, str],
) -> tuple[list[str], dict[str, str], list[str]]:
    """Возвращает строки файла, ожидаемые значения и предупреждения."""
    lines: list[str] = []
    expected: dict[str, str] = {}
    warnings: list[str] = []

    if options.qdisc is not None:
        qdisc = options.qdisc
        available = set(_available_qdiscs())
        if qdisc == "auto":
            qdisc = "cake" if "cake" in available else "fq"
        if qdisc not in {"fq", "cake"}:
            raise TweakError(f"Неизвестная qdisc: {qdisc}")
        if qdisc not in available:
            warnings.append(
                f"{qdisc} недоступна; использую fq."
            )
            qdisc = "fq"
        lines.append(f"net.core.default_qdisc = {qdisc}")
        expected["net.core.default_qdisc"] = qdisc

    if options.bbr:
        if _bbr_available():
            lines.append("net.ipv4.tcp_congestion_control = bbr")
            expected["net.ipv4.tcp_congestion_control"] = "bbr"
        else:
            warnings.append(
                "BBR не найден в tcp_available_congestion_control; "
                "параметр пропущен."
            )

    if options.netdev_backlog:
        try:
            backlog = int(current.get("net.core.netdev_max_backlog", "0"))
        except ValueError:
            backlog = 0
        if backlog < 4096:
            lines.append("net.core.netdev_max_backlog = 4096")
            expected["net.core.netdev_max_backlog"] = "4096"
        elif backlog:
            warnings.append(
                "netdev_max_backlog уже не ниже 4096; не понижаю."
            )

    if options.tcp_fastopen:
        lines.append("net.ipv4.tcp_fastopen = 3")
        expected["net.ipv4.tcp_fastopen"] = "3"

    if options.tcp_mtu_probing:
        try:
            probing = int(current.get("net.ipv4.tcp_mtu_probing", "0"))
        except ValueError:
            probing = 0
        if probing < 1:
            lines.append("net.ipv4.tcp_mtu_probing = 1")
            expected["net.ipv4.tcp_mtu_probing"] = "1"
        elif probing > 1:
            warnings.append(
                "tcp_mtu_probing уже агрессивнее 1; не понижаю."
            )

    if options.ip_forward:
        lines.append("net.ipv4.ip_forward = 1")
        expected["net.ipv4.ip_forward"] = "1"

    return lines, expected, warnings


def _verify_expected(expected: dict[str, str]) -> list[str]:
    current = _read_values()
    problems: list[str] = []
    for key, value in expected.items():
        actual = current.get(key)
        if actual != value:
            problems.append(
                f"{key}: ожидалось {value}, получено {actual or '—'}"
            )
    return problems


def _apply(options: TweakOptions) -> TweakResult:
    current = _read_values()
    previous_keys = _managed_keys()
    lines, expected, warnings = _build_lines(options, current)
    if not lines:
        return TweakResult(
            True,
            "Изменения не требуются: выбранные параметры уже применены.",
            output="\n".join(warnings),
        )

    try:
        before = _load_before()
        file_existed = SYSCTL_FILE.exists()
        file_backup = _backup_existing_file()
        if before is None:
            _save_before(
                current,
                file_existed=file_existed,
                file_backup=file_backup,
            )
            before = _load_before()
    except TweakError as exc:
        return TweakResult(False, str(exc))

    if before is None:
        return TweakResult(
            False,
            "Не удалось сохранить точку возврата; изменения не применены.",
        )

    # Если пользователь снял ранее включённую галочку, возвращаем исходное
    # значение, а не оставляем его в ядре до перезагрузки.
    reset_values: dict[str, str] = {}
    before_values = before.get("values")
    if previous_keys and isinstance(before_values, dict):
        for key in sorted(previous_keys - set(expected)):
            value = before_values.get(key)
            if (
                isinstance(value, str)
                and value
                and value != current.get(key)
            ):
                reset_values[key] = value

    header = [
        _FILE_MARKER,
        "# Обновлено: " + datetime.now(timezone.utc).isoformat(
            timespec="seconds"
        ),
    ]
    text = "\n".join([*header, *lines]) + "\n"
    verify_expected = dict(expected)
    verify_expected.update(reset_values)
    try:
        _write_atomic(SYSCTL_FILE, text, 0o644)
        _run_sysctl(SYSCTL_FILE, description="сетевые твики")
        if reset_values:
            _apply_values(
                reset_values,
                description="ранее применённые твики",
            )
        problems = _verify_expected(verify_expected)
        if problems:
            raise TweakError(
                "Проверка sysctl не прошла:\n" + "\n".join(problems)
            )
    except TweakError as exc:
        rollback_errors: list[str] = []
        try:
            _apply_values(current, description="старые sysctl-значения")
        except TweakError as rollback_exc:
            rollback_errors.append(str(rollback_exc))
        try:
            _restore_file(before)
        except TweakError as rollback_exc:
            rollback_errors.append(str(rollback_exc))
        message = str(exc)
        if rollback_errors:
            message += "\nRollback: " + " | ".join(rollback_errors)
        return TweakResult(False, message)

    message = (
        "Сетевые твики применены: "
        + ", ".join(key.rsplit(".", 1)[-1] for key in expected)
        + f".\nФайл: {SYSCTL_FILE}"
    )
    if reset_values:
        message += (
            "\nСнято и возвращено: "
            + ", ".join(
                key.rsplit(".", 1)[-1] for key in reset_values
            )
        )
    if file_backup:
        message += f"\nBackup: {file_backup}"
    if warnings:
        message += "\n\n" + "\n".join(warnings)
    return TweakResult(True, message)


def _revert() -> TweakResult:
    before = _load_before()
    if before is None:
        if SYSCTL_FILE.exists() and _read_file_marker():
            try:
                SYSCTL_FILE.unlink()
            except OSError as exc:
                return TweakResult(False, f"Не удалось удалить файл: {exc}")
            return TweakResult(True, "Файл твиков удалён.")
        return TweakResult(
            False,
            "Нет сохранённой точки возврата: откатывать нечего.",
        )

    values = before.get("values")
    if not isinstance(values, dict):
        return TweakResult(False, "Повреждён before.json; откат невозможен.")
    clean_values = {
        str(key): str(value)
        for key, value in values.items()
        if isinstance(key, str)
        and isinstance(value, str)
        and key in SYSCTL_KEYS
        and value
    }
    try:
        _apply_values(clean_values, description="старые sysctl-значения")
        problems = _verify_expected(clean_values)
        if problems:
            raise TweakError(
                "Проверка отката не прошла:\n" + "\n".join(problems)
            )
        _restore_file(before)
        BEFORE_FILE.unlink(missing_ok=True)
    except TweakError as exc:
        return TweakResult(False, str(exc))
    except OSError as exc:
        return TweakResult(False, f"Не удалось завершить откат: {exc}")
    return TweakResult(
        True,
        "Твики удалены, старые значения восстановлены.",
    )


def _ensure_root() -> None:
    if os.geteuid() != 0:
        raise TweakError("Root-worker твиков должен запускаться через pkexec.")


def _parse_options(value: object) -> TweakOptions:
    if not isinstance(value, dict):
        raise TweakError("Некорректные параметры твиков.")
    qdisc = value.get("qdisc", "auto")
    if qdisc is not None and qdisc not in {"auto", "fq", "cake"}:
        raise TweakError("Некорректная qdisc.")
    return TweakOptions(
        qdisc=qdisc,
        bbr=bool(value.get("bbr", True)),
        netdev_backlog=bool(value.get("netdev_backlog", True)),
        tcp_fastopen=bool(value.get("tcp_fastopen", True)),
        tcp_mtu_probing=bool(value.get("tcp_mtu_probing", True)),
        ip_forward=bool(value.get("ip_forward", False)),
    )


def _execute_plan(payload: dict[str, Any]) -> TweakResult:
    _ensure_root()
    action = payload.get("action")
    if action == "apply":
        return _apply(_parse_options(payload.get("options")))
    if action == "revert":
        return _revert()
    raise TweakError(f"Неизвестное действие твиков: {action!r}")


def _parse_worker_result(stdout: str) -> TweakResult | None:
    for line in reversed(stdout.splitlines()):
        line = line.strip()
        if not line:
            continue
        try:
            data = json.loads(line)
        except ValueError:
            continue
        if not isinstance(data, dict) or "ok" not in data:
            continue
        return TweakResult(
            ok=bool(data.get("ok")),
            message=str(data.get("message", "")),
            output=str(data.get("output", "")),
            returncode=data.get("returncode")
            if isinstance(data.get("returncode"), int)
            else None,
        )
    return None


class TweakManager:
    """Пользовательский API для чтения статуса и применения твиков."""

    def status(self) -> TweakStatus:
        backups: list[Path] = []
        if BACKUP_DIR.is_dir():
            backups = sorted(
                BACKUP_DIR.glob("99-zapret-easy.conf.*.bak"),
                key=lambda path: path.stat().st_mtime_ns
                if path.exists()
                else 0,
            )
        return TweakStatus(
            file_exists=SYSCTL_FILE.is_file(),
            file_ours=_read_file_marker(),
            current=_read_values(),
            qdiscs=_available_qdiscs(),
            bbr_available=_bbr_available(),
            before_file=BEFORE_FILE.is_file(),
            backup_file=backups[-1] if backups else None,
        )

    def apply(self, options: TweakOptions) -> TweakResult:
        payload = {
            "version": 1,
            "action": "apply",
            "options": asdict(options),
        }
        return _run_root(payload)

    def revert(self) -> TweakResult:
        return _run_root({"version": 1, "action": "revert"})


def _run_root(payload: dict[str, Any]) -> TweakResult:
    if os.geteuid() == 0:
        try:
            return _execute_plan(payload)
        except TweakError as exc:
            return TweakResult(False, str(exc))

    pkexec = shutil.which("pkexec")
    if pkexec is None:
        return TweakResult(
            False,
            "pkexec не найден: нельзя применить системные твики.",
        )
    python = Path(sys.executable)
    if not python.is_absolute():
        python = Path("/usr/bin/python3")
    project = str(PROJECT_ROOT)
    bootstrap = (
        "import sys;"
        f"sys.path.insert(0, {project!r});"
        "from src.tweaks import worker_main;"
        "raise SystemExit(worker_main())"
    )
    try:
        completed = subprocess.run(
            [pkexec, str(python), "-c", bootstrap, "--worker"],
            input=json.dumps(payload, ensure_ascii=False) + "\n",
            capture_output=True,
            text=True,
            timeout=60.0,
            check=False,
            cwd=PROJECT_ROOT,
            env=_base_env(),
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return TweakResult(False, f"Не удалось запустить pkexec: {exc}")

    result = _parse_worker_result(completed.stdout)
    if result is not None:
        return result

    stderr = completed.stderr.strip()
    if completed.returncode == 126:
        message = "Авторизация pkexec отменена или недоступна."
    elif completed.returncode == 127:
        message = "pkexec не разрешил выполнение root-операции."
    else:
        message = (
            "root-worker твиков завершился без результата "
            f"(код {completed.returncode})."
        )
    if stderr:
        message += f"\n{stderr}"
    return TweakResult(
        False,
        message,
        output=stderr,
        returncode=completed.returncode,
    )


def _emit_result(result: TweakResult) -> None:
    sys.stdout.write(
        json.dumps(asdict(result), ensure_ascii=False) + "\n"
    )
    sys.stdout.flush()


def worker_main() -> int:
    """Точка входа root-worker-а: одна JSON-строка на stdin."""
    try:
        raw = sys.stdin.buffer.readline(MAX_WORKER_LINE + 1)
        if not raw:
            raise TweakError("Не получен план твиков.")
        if len(raw) > MAX_WORKER_LINE:
            raise TweakError("План твиков слишком большой.")
        try:
            payload = json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, ValueError) as exc:
            raise TweakError(f"Некорректный JSON плана: {exc}") from exc
        if not isinstance(payload, dict):
            raise TweakError("План твиков должен быть JSON-объектом.")
        result = _execute_plan(payload)
    except TweakError as exc:
        result = TweakResult(False, str(exc))
    except Exception as exc:  # noqa: BLE001 - worker обязан вернуть JSON
        logger.exception("Ошибка root-worker-а твиков")
        result = TweakResult(False, f"Внутренняя ошибка твиков: {exc}")
    _emit_result(result)
    return 0 if result.ok else 1


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if "--worker" in args:
        return worker_main()

    manager = TweakManager()
    if "--apply" in args:
        result = manager.apply(TweakOptions())
        print(result.message)
        return 0 if result.ok else 1
    if "--revert" in args:
        result = manager.revert()
        print(result.message)
        return 0 if result.ok else 1

    status = manager.status()
    print(f"Файл:      {SYSCTL_FILE} ({'есть' if status.file_exists else 'нет'})")
    print(f"Наш файл:  {'да' if status.file_ours else 'нет'}")
    print(f"qdisc:     {', '.join(status.qdiscs)}")
    print(f"BBR:       {'да' if status.bbr_available else 'нет'}")
    print("Текущие значения:")
    for key, value in status.current.items():
        print(f"  {key} = {value}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
